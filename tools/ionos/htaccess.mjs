// .htaccess for the IONOS webspace (docs/HOSTING-IONOS.md), generated from the same sources as server.mjs:
//   redirects    src/config/redirects.mjs (REDIRECTS and the product pattern)
//   headers      SECURITY_HEADERS as in server.mjs, HSTS once HTTPS is detected
//   caching      cacheControl() and TYPES of server-static.mjs
// Never edit the output by hand: tools/ionos/prepare.mjs writes it on every build, and
// tests/ionos-htaccess.test.mjs replays its rules against redirectTarget().
// Apache delivers byte ranges (206) for static files by itself; nothing to configure for video.
import { REDIRECTS } from '../../src/config/redirects.mjs';
import { TYPES, COMPRESSIBLE } from '../../server-static.mjs';

// Kept in step with server.mjs by tests/ionos-htaccess.test.mjs (server.mjs does not export them).
export const SECURITY_HEADERS = {
  'Content-Security-Policy': "frame-ancestors 'none'",
  'X-Frame-Options': 'DENY',
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Resource-Policy': 'same-origin',
};
export const HSTS = 'max-age=31536000; includeSubDomains';

const HANDLE = '[a-z0-9][a-z0-9-]*';
const PRODUCT_PREFIX = `(?:collections/${HANDLE}/)?products/`;

const escapeRegex = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * @param {object} options
 * @param {string} options.origin          canonical origin, e.g. https://royalspices.de (targets are absolute: one hop from http and www)
 * @param {string[]} [options.productHandles] handles with a built product page; matched in any case
 * @returns {string}
 */
export function buildHtaccess({ origin, productHandles = [] }) {
  const url = new URL(origin);
  if (url.pathname !== '/' || url.search || url.hash) throw new Error(`origin without path expected: ${origin}`);
  const base = url.origin;
  const secure = url.protocol === 'https:';
  const host = url.host;
  const out = [];
  const line = (s = '') => out.push(s);

  line('# Generated by tools/ionos/htaccess.mjs from src/config/redirects.mjs and server-static.mjs.');
  line('# Do not edit: every build overwrites this file (docs/HOSTING-IONOS.md).');
  line();
  line('Options -Indexes');
  line('DirectoryIndex index.html index.php');
  line('# trailing slashes are added below, in the same hop as https and the canonical host');
  line('DirectorySlash Off');
  line('ErrorDocument 404 /404.html');
  line('FileETag MTime Size');
  line();
  line('# content types (server-static.mjs TYPES)');
  line('<IfModule mod_mime.c>');
  for (const [ext, type] of Object.entries(TYPES)) line(`  AddType "${type}" ${ext}`);
  line('</IfModule>');
  line();
  line('RewriteEngine On');
  line('RewriteBase /');
  line();
  line('# hidden files (except .well-known) and PHP outside the inquiry endpoint do not exist');
  line('RewriteRule (?:^|/)\\.(?!well-known/) - [R=404,L]');
  line('RewriteCond %{REQUEST_URI} !^/api/anfrage/(?:index\\.php)?$');
  line('RewriteRule \\.(?:php|phtml|phar|inc)$ - [NC,R=404,L]');
  line();
  line('# pages are GET and HEAD only; /api/ answers for itself');
  line('RewriteCond %{REQUEST_METHOD} !^(?:GET|HEAD)$');
  line('RewriteRule !^api/ - [R=405,L]');
  line();
  line('# old shop and page URLs (src/config/redirects.mjs): one permanent hop, query string kept');
  for (const [from, to] of REDIRECTS) {
    line(`RewriteRule ^${escapeRegex(from.slice(1))}/*$ ${base}${to} [NC,R=301,L]`);
  }
  line('# Shopify product URLs, also collection-scoped. Built products match in any case;');
  line('# other handles only in lower case (Apache cannot lower-case in .htaccess).');
  for (const handle of productHandles) {
    if (!new RegExp(`^${HANDLE}$`).test(handle)) throw new Error(`unexpected product handle: ${handle}`);
    line(`RewriteRule ^${PRODUCT_PREFIX}${escapeRegex(handle)}/*$ ${base}/produkte/${handle}/ [NC,R=301,L]`);
  }
  line(`RewriteCond $1 ^${HANDLE}$`);
  line(`RewriteRule ^${PRODUCT_PREFIX}(${HANDLE})/*$ ${base}/produkte/$1/ [NC,R=301,L]`);
  line();
  line('# folders without trailing slash: one hop to the canonical URL');
  line('RewriteCond %{REQUEST_FILENAME} -d');
  line(`RewriteRule ^(.*[^/])$ ${base}/$1/ [R=301,L]`);
  line();
  line('# canonical scheme and host');
  if (secure) {
    line('RewriteCond %{HTTPS} !=on');
    line('RewriteCond %{HTTP:X-Forwarded-Proto} !=https');
    line(`RewriteRule ^ ${base}%{REQUEST_URI} [R=301,L]`);
  }
  line(`RewriteCond %{HTTP_HOST} !=${host}`);
  line(`RewriteRule ^ ${base}%{REQUEST_URI} [R=301,L]`);
  line();
  line('<IfModule mod_headers.c>');
  line('  # security headers of server.mjs, on every response including redirects and errors');
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) line(`  Header always set ${name} "${value}"`);
  line(`  Header always set Strict-Transport-Security "${HSTS}" "expr=%{HTTPS} == 'on' || %{HTTP:X-Forwarded-Proto} == 'https'"`);
  line('  Header always set Allow "GET, HEAD" "expr=%{REQUEST_STATUS} == 405 && %{REQUEST_URI} !~ m#^/api/#"');
  line('  # cache policy of server-static.mjs cacheControl(); /api/ sets its own (no-store)');
  line('  <If "%{REQUEST_URI} =~ m#^/(?:_astro|video)/#">');
  line('    Header set Cache-Control "public, max-age=31536000, immutable"');
  line('  </If>');
  line('  <ElseIf "%{REQUEST_URI} =~ m#^/(?:hero|img)/#">');
  line('    Header set Cache-Control "public, max-age=604800, stale-while-revalidate=86400"');
  line('  </ElseIf>');
  line('  <ElseIf "%{REQUEST_URI} =~ m#(?:\\.html|/)$# && %{REQUEST_URI} !~ m#^/api/#">');
  line('    Header set Cache-Control "public, max-age=0, must-revalidate"');
  line('  </ElseIf>');
  line('  <ElseIf "%{REQUEST_URI} !~ m#^/api/#">');
  line('    Header set Cache-Control "public, max-age=3600"');
  line('  </ElseIf>');
  line('</IfModule>');
  line();
  const compressible = [...COMPRESSIBLE].map((ext) => TYPES[ext].split(';')[0]);
  const types = [...new Set(compressible)].join(' ');
  line('# compression for text; images, fonts and video are already compressed');
  line('<IfModule mod_brotli.c>');
  line(`  AddOutputFilterByType BROTLI_COMPRESS ${types}`);
  line('</IfModule>');
  line('<IfModule !mod_brotli.c>');
  line('  <IfModule mod_deflate.c>');
  line(`    AddOutputFilterByType DEFLATE ${types}`);
  line('  </IfModule>');
  line('</IfModule>');
  return out.join('\n') + '\n';
}

export { escapeRegex };
